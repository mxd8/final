/**
 * 导出侧格式化：记录 → Surge 规则文本、IP 版本标记、筛选描述、注释头与摘要。
 */

import { canonicalIp, formatRuleItem } from '../surge-rule/index.js';
import { normalizeRuleType } from './normalize.js';

/**
 * 记录 → 导出用的规范化 (type, value)：单个 IP 补 /32 或 /128。
 * formatLogRule 与 markExportIpVersion 共用这一个入口，
 * buildExport 传入同一份结果即可避免同一行跑两轮 IP 规范化。
 */
export function canonicalizeLogItem(item) {
  return canonicalIp(normalizeRuleType(item?.type), item?.value);
}

/** 把记录格式化成 Surge 规则文本；可传入 canonicalizeLogItem 的结果跳过重复规范化 */
export function formatLogRule(item, { withSource = false, canonical } = {}) {
  const normalized = canonical ?? canonicalizeLogItem(item);
  const { type, value } = normalized;
  const text = formatRuleItem({
    type,
    value,
    policy: item.policy,
    params: item.params,
    comment: item.comment
  });
  if (!withSource || !item.source) return text;
  return `${text} // 来源：${item.source}`;
}

/**
 * 给记录打上 IP 版本标记，供导出摘要统计 IPv4 / IPv6 条数。
 * 与 formatLogRule 走同一个 canonicalizeLogItem，保证统计口径与导出文本一致。
 */
export function markExportIpVersion(item) {
  return markIpVersionFromCanonical(item, canonicalizeLogItem(item));
}

/** 同上，但接受已算好的 canonical 结果，导出主循环用它避免二次规范化 */
export function markIpVersionFromCanonical(item, canonical) {
  const { type, value } = canonical;
  const text = String(value || '');
  if (type !== 'IP-CIDR' && type !== 'IP-CIDR6' && !text.includes(':')) return { ...item, ipv4: false, ipv6: false };
  if (type === 'IP-CIDR6' || text.includes(':')) return { ...item, ipv4: false, ipv6: true };
  return { ...item, ipv4: true, ipv6: false };
}

/** 导出筛选条件 → 结构化描述；导出与摘要共用，保证「说的」与「做的」一致 */
export function describeExportFilter({ type = 'all', source = '', minCount = 0, lastDays = 0 } = {}) {
  const typeText = String(type || 'all').trim().toUpperCase() || 'ALL';
  const sourceText = String(source || '').trim();
  const min = Math.floor(Number(minCount) || 0);
  const days = Math.floor(Number(lastDays) || 0);
  const parts = [`type=${typeText === 'ALL' ? 'ALL' : typeText}`, `source=${sourceText || 'ANY'}`];
  if (min > 1) parts.push(`min_count=${min}`);
  if (days > 0) parts.push(`last_days=${days}`);
  return { type: typeText, source: sourceText, minCount: min, lastDays: days, text: parts.join(', ') };
}

function tallyByField(lines) {
  const byPolicy = {};
  const byType = {};
  let ipv4 = 0;
  let ipv6 = 0;
  for (const item of lines) {
    const policy = String(item.policy || 'PROXY').toUpperCase();
    const type = String(item.type || 'DOMAIN-SUFFIX').toUpperCase();
    byPolicy[policy] = (byPolicy[policy] || 0) + 1;
    byType[type] = (byType[type] || 0) + 1;
    if (item.ipv4) ipv4 += 1;
    if (item.ipv6) ipv6 += 1;
  }
  return { byPolicy, byType, ipv4, ipv6 };
}

function tallyText(map) {
  return Object.entries(map)
    .sort((a, b) => b[1] - a[1])
    .map(([name, count]) => `${name}: ${count}`)
    .join(' | ');
}

/** 订阅顶部元数据注释；全部单行 # 前缀（#!xxx 是 Surge 元数据键，不可占用） */
export function buildExportHeader({ filterText = 'type=ALL, source=ANY', lines = [], hits = 0, generatedAt = '' } = {}) {
  const counts = tallyByField(lines);
  const policyText = tallyText(counts.byPolicy);
  return [
    `# Generated by Surge Rules Manager at ${generatedAt || '-'}`,
    `# Filter: ${filterText}`,
    `# Rules: ${lines.length} total${policyText ? ` | ${policyText}` : ''}`,
    `# Types: ${tallyText(counts.byType) || 'none'}`,
    `# Hits: total ${Math.max(0, Number(hits) || 0)} | IPv4: ${counts.ipv4} | IPv6: ${counts.ipv6}`
  ];
}

/** 导出摘要：与导出文本用同一批格式化结果计算，摘要数字和实际导出行数必然一致 */
export function summarizeExport(lines = []) {
  const counts = tallyByField(lines);
  let hits = 0;
  let emptyComment = 0;
  for (const item of lines) {
    hits += Number(item.count) || 1;
    if (!String(item.comment || '').trim()) emptyComment += 1;
  }
  return {
    ruleCount: lines.length,
    hits,
    ipv4: counts.ipv4,
    ipv6: counts.ipv6,
    emptyComment,
    byPolicy: counts.byPolicy,
    byType: counts.byType
  };
}
